#!/usr/bin/env python3
"""Generate this demo environment's secrets and demo-account credentials.

Everything it writes goes to ``~/sip-demo`` (mode 0700), never into the
repository. The repo is public, so no generated secret, password or hash is
written anywhere under the working tree.

Outputs
-------
``~/sip-demo/secrets.env``      infra secrets for ``docker compose --env-file``
``~/sip-demo/accounts.json``    demo accounts + argon2id hashes (for the provisioner)
``~/sip-demo/credentials.txt``  the human handoff sheet

Idempotent: existing files are reused, so restarting the environment never
changes a password. Pass ``--force`` to rotate everything.

The argon2id parameters match SIP's ``Argon2::default()`` exactly
(argon2 v0.5.3: Argon2id, v19, m=19456, t=2, p=1, 32-byte output). That
compatibility is asserted by ``crates/sip-auth/tests/external_hash_compat.rs``.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import secrets
import stat
import string
import sys
from pathlib import Path

OUT_DIR = Path.home() / "sip-demo"
HERMES_ENV = Path.home() / ".hermes" / ".env"

TENANT_NAME = "SIP Demo Rail Services"
TENANT_SLUG = "sip-demo-rail-services"
EMAIL_DOMAIN = "sip-demo.local"

# Role -> (local part, display name). Role names are SIP's own UserRole values.
ROLES = [
    ("ADMIN", "admin", "Demo Administrator"),
    ("MANAGER", "manager", "Demo Maintenance Manager"),
    ("TECHNICIAN", "tech", "Demo Technician"),
    ("VIEWER", "viewer", "Demo Read-Only Viewer"),
    ("VENDOR", "vendor", "Demo External Vendor"),
    ("AUDITOR", "auditor", "Demo Compliance Auditor"),
]

ALPHABET = string.ascii_letters + string.digits


def human_password(groups: int = 4, size: int = 4) -> str:
    """A strong but typable password, e.g. 'Kf7m-Pq2x-Rt9w-Zb4n' (≈95 bits)."""
    return "-".join(
        "".join(secrets.choice(ALPHABET) for _ in range(size)) for _ in range(groups)
    )


def machine_secret(nbytes: int = 32) -> str:
    return secrets.token_urlsafe(nbytes)


def read_hermes_key(name: str) -> str | None:
    """Read a key from ~/.hermes/.env without echoing it."""
    if not HERMES_ENV.is_file():
        return None
    for line in HERMES_ENV.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        if k.strip() == name:
            return v.strip().strip('"').strip("'")
    return None


def hash_password(password: str) -> str:
    try:
        from argon2 import PasswordHasher
        from argon2.low_level import Type
    except ImportError:
        sys.exit(
            "argon2-cffi is required. Install it with:\n"
            "  ~/.venvs/sip-data/bin/pip install argon2-cffi"
        )
    ph = PasswordHasher(
        time_cost=2, memory_cost=19456, parallelism=1,
        hash_len=32, salt_len=16, type=Type.ID,
    )
    return ph.hash(password)


DEMO_TOML = """# Generated by scripts/demo/gen_env.py for the isolated demo stack.
#
# Mounted read-only over /app/Sip.toml in the demo Compose project. Configuration
# precedence is hardcoded defaults < this file < SIP_* environment variables, so
# anything secret stays in the env-file and never appears here.

[server]
port = 8000

[features]
plugin_system_enabled = true
marketplace_enabled = true

[security]
# The demo stack serves its frontend on its own port, and the browser calls the
# API cross-origin, so the frontend's origin has to be allowed explicitly.
# Setting this through the environment would depend on figment parsing a list out
# of a string; a TOML file expresses it unambiguously.
cors_allowed_origins = ["http://localhost:{frontend_port}"]
"""


def write_demo_toml(frontend_port: int = 13000) -> None:
    """Always rewritten: it contains no secrets and must track the overlay."""
    path = OUT_DIR / "demo.toml"
    path.write_text(DEMO_TOML.format(frontend_port=frontend_port))
    print(f"  demo.toml        {path.name}  (CORS origin http://localhost:{frontend_port})")


def write_private(path: Path, text: str) -> None:
    path.write_text(text)
    os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)  # 0600


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--force", action="store_true", help="rotate everything, even if it exists")
    args = ap.parse_args()

    OUT_DIR.mkdir(mode=0o700, exist_ok=True)
    os.chmod(OUT_DIR, 0o700)

    secrets_path = OUT_DIR / "secrets.env"
    accounts_path = OUT_DIR / "accounts.json"

    if secrets_path.exists() and accounts_path.exists() and not args.force:
        accounts = json.loads(accounts_path.read_text())
        print(f"reusing existing environment in {OUT_DIR} (pass --force to rotate)")
        print(f"  tenant : {accounts['tenant_name']} ({accounts['tenant_slug']})")
        print(f"  accounts: {len(accounts['accounts'])}")
        print(f"  handoff : {OUT_DIR / 'credentials.txt'}")
        write_demo_toml()
        return

    deepseek = read_hermes_key("DEEPSEEK_API_KEY")
    if not deepseek:
        print("WARNING: DEEPSEEK_API_KEY not found in ~/.hermes/.env; AI will be disabled.")

    postgres_password = machine_secret(24)
    minio_password = machine_secret(24)
    jwt_secret = machine_secret(48)

    accounts = []
    for role, local, name in ROLES:
        accounts.append(
            {
                "role": role,
                "email": f"{local}@{EMAIL_DOMAIN}",
                "name": name,
                "password": human_password(),
            }
        )
    for acct in accounts:
        acct["password_hash"] = hash_password(acct["password"])

    payload = {
        "tenant_name": TENANT_NAME,
        "tenant_slug": TENANT_SLUG,
        "email_domain": EMAIL_DOMAIN,
        "accounts": accounts,
    }
    write_private(accounts_path, json.dumps(payload, indent=2) + "\n")

    # Infra secrets, consumed by docker compose via --env-file.
    lines = [
        "# Generated by scripts/demo/gen_env.py — DO NOT COMMIT.",
        "# Used as: docker compose --env-file <this file> ...",
        f"POSTGRES_PASSWORD={postgres_password}",
        f"MINIO_ROOT_PASSWORD={minio_password}",
        f"JWT_SECRET={jwt_secret}",
        "AI_ENABLED=true",
        "AI_PROVIDER=openai",
        "AI_MODEL=deepseek-chat",
        "AI_BASE_URL=https://api.deepseek.com/v1",
    ]
    if deepseek:
        lines.append(f"SIP_DEEPSEEK_API_KEY={deepseek}")
    write_private(secrets_path, "\n".join(lines) + "\n")

    # Human handoff sheet. Application credentials and infrastructure
    # credentials are deliberately kept in separate sections.
    sheet = [
        "SIP DEMO ENVIRONMENT — PRIVATE CREDENTIALS",
        "=" * 52,
        "Generated locally. Not committed. Do not publish.",
        "",
        f"Tenant (customer): {TENANT_NAME}",
        f"Tenant slug:       {TENANT_SLUG}",
        "",
        "APPLICATION ACCOUNTS  (sign in at the SIP login screen)",
        "-" * 52,
    ]
    for acct in accounts:
        sheet.append(f"  {acct['role']:<11} {acct['email']}")
        sheet.append(f"  {'':<11} password: {acct['password']}")
        sheet.append("")
    sheet += [
        "INFRASTRUCTURE ACCESS  (local demo only — not application logins)",
        "-" * 52,
        f"  Postgres  user sip / password {postgres_password}",
        "            not published to the host; reach it with:",
        "            sudo docker exec -it sip-postgres psql -U sip -d sip",
        f"  MinIO     console http://localhost:9001  user minioadmin / password {minio_password}",
        "  JWT secret for this environment (overrides the dev default):",
        f"            {jwt_secret}",
        "",
        "File locations",
        "-" * 52,
        f"  infra secrets : {secrets_path}",
        f"  machine-readable accounts : {accounts_path}",
    ]
    write_private(OUT_DIR / "credentials.txt", "\n".join(sheet) + "\n")
    write_demo_toml()

    print(f"wrote {OUT_DIR} (mode 0700)")
    print(f"  secrets.env      {secrets_path.name}")
    print(f"  accounts.json    {accounts_path.name}  ({len(accounts)} accounts)")
    print(f"  credentials.txt  credential handoff sheet")
    print(f"  AI provider key  {'present (from ~/.hermes/.env)' if deepseek else 'MISSING'}")


if __name__ == "__main__":
    main()
